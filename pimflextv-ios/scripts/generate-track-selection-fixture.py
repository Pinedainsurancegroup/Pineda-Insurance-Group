#!/usr/bin/env python3
"""Generate original, offline DEBUG media; requires ffmpeg with libx264/AAC.

No APK assets, fonts, provider streams or credentials are used. The video is
made from colored rectangles; two quiet sine waves and two original subtitle
texts make the tracks distinguishable. The existing playback fixtures are
never read or replaced. Codec versions may change the generated bytes.

Example (refuses to replace an existing output):
  python3 scripts/generate-track-selection-fixture.py --output /tmp/TrackSelectionFixture.mp4
"""
import argparse
from pathlib import Path
import subprocess
import tempfile


def timestamp(seconds):
    return f"{seconds // 3600:02}:{seconds // 60 % 60:02}:{seconds % 60:02},000"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", required=True, type=Path)
    output = parser.parse_args().output.expanduser().absolute()
    if output.exists() or output.is_symlink():
        parser.error("Output already exists; choose a new path.")
    if not output.parent.is_dir():
        parser.error("Output directory must already exist.")
    with tempfile.TemporaryDirectory(prefix="pimflex-track-fixture-") as temporary:
        subtitles = []
        for language, text in [("spa", "PRUEBA LOCAL: SUBTITULO ESPANOL"),
                               ("eng", "LOCAL TEST: ENGLISH SUBTITLE")]:
            path = Path(temporary) / f"{language}.srt"
            path.write_text("\n".join(
                f"{index + 1}\n{timestamp(start)} --> {timestamp(start + 5)}\n{text}\n"
                for index, start in enumerate(range(0, 300, 5))), encoding="utf-8")
            subtitles.append(path)
        subprocess.run([
            "ffmpeg", "-hide_banner", "-loglevel", "error", "-nostdin", "-n",
            "-f", "lavfi", "-i",
            "color=c=0x14324F:s=640x360:r=2:d=300,"
            "drawbox=x=80:y=50:w=480:h=160:color=0x40A8C4:t=fill,"
            "drawbox=x=100:y=70:w=440:h=120:color=0x14324F:t=fill",
            "-f", "lavfi", "-i", "sine=frequency=440:sample_rate=22050:duration=300,volume=0.25",
            "-f", "lavfi", "-i", "sine=frequency=880:sample_rate=22050:duration=300,volume=0.25",
            "-i", str(subtitles[0]), "-i", str(subtitles[1]),
            "-map", "0:v:0", "-map", "1:a:0", "-map", "2:a:0", "-map", "3:s:0", "-map", "4:s:0",
            "-c:v", "libx264", "-preset", "medium", "-crf", "32", "-pix_fmt", "yuv420p",
            "-profile:v", "baseline", "-level:v", "3.0", "-g", "4", "-threads", "1",
            "-c:a", "aac", "-b:a", "32k", "-ac", "1", "-c:s", "mov_text",
            "-metadata:s:a:0", "language=spa", "-metadata:s:a:0", "handler_name=Spanish 440 Hz",
            "-metadata:s:a:1", "language=eng", "-metadata:s:a:1", "handler_name=English 880 Hz",
            "-metadata:s:s:0", "language=spa", "-metadata:s:s:0", "handler_name=Spanish local test",
            "-metadata:s:s:1", "language=eng", "-metadata:s:s:1", "handler_name=English local test",
            "-disposition:a:0", "default", "-disposition:a:1", "0",
            "-disposition:s:0", "0", "-disposition:s:1", "0",
            "-metadata", "title=PIMFLEX original local track selection test",
            "-metadata", "comment=Generated synthetic DEBUG media; no provider or APK content",
            "-movflags", "+faststart", "-t", "300", str(output),
        ], check=True)
    print(output)


if __name__ == "__main__":
    main()
